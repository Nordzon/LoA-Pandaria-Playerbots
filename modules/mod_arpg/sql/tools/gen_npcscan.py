"""Generates arpg/addons/ArpgNPCScan/Data.lua for the ArpgNPCScan helper addon (owner 2026-11-28: "Create the NPC scan list"):
  Watch  = every Superunique's "Unique <name>" copy (entry + 700000), so _NPCScan alerts on it;
  Ignore = the pooled rares themselves (rank 2/4): the server swaps them for their Unique copy on sight, so an alert for the
           original would be a false one.
Re-run after gen_superuniques.py / gen_monster_tags.py, then arpg/scripts/install-addons.ps1. Usage: py -I gen_npcscan.py
"""
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
MYSQL = r'C:\Program Files\MySQL\MySQL Server 8.0\bin\mysql.exe'
CNF = os.path.join(ROOT, 'arpg', 'scripts', 'mysql.local.cnf')
OUT = os.path.join(ROOT, 'arpg', 'addons', 'ArpgNPCScan', 'Data.lua')
UNIQUE_OFFSET = 700000
BACKSLASH = chr(92)


def q(sql):
    out = subprocess.run([MYSQL, '--defaults-extra-file=' + CNF, '-D', 'world', '-B', '-N', '-e', sql],
                         capture_output=True, text=True, check=True).stdout
    return [line.split('\t') for line in out.splitlines() if line]


def lua_str(s):
    return '"' + s.replace(BACKSLASH, BACKSLASH * 2).replace('"', BACKSLASH + '"') + '"'


watch = q("SELECT DISTINCT u.entry, u.name FROM arpg_superunique s JOIN creature_template u ON u.entry = s.creature_entry + %d "
          "ORDER BY u.entry" % UNIQUE_OFFSET)
ignore = q("SELECT DISTINCT t.entry, t.name FROM arpg_superunique s JOIN creature_template t ON t.entry = s.creature_entry "
           "WHERE t.`rank` IN (2, 4) ORDER BY t.entry")
lines = ['-- GENERATED by modules/mod_arpg/sql/tools/gen_npcscan.py - do not edit by hand.',
         'ArpgNPCScanData = {', '    watch = {']
lines += ['        [%s] = %s,' % (e, lua_str(n)) for e, n in watch]
lines += ['    },', '    ignore = {']
lines += ['        [%s] = %s,' % (e, lua_str(n)) for e, n in ignore]
lines += ['    },', '}']
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print('wrote %s: %d to watch, %d to ignore' % (OUT, len(watch), len(ignore)))
