"""Generates the ArpgGatherData client addon (owner 2026-11-28: a GatherMate2 database from OUR server, exact for its spawns):
every herb, ore, gas cloud, treasure and fishing pool spawned in the world DB, as GatherMate2 1.27 (the last 5.4.8 build) stores
them: per node type, per map area ID (WorldMapArea.dbc, what GetCurrentMapAreaID returns), coordinate key
floor(x*10000+0.5)*1000000 + floor(y*10000+0.5)*100 (+ floor level 0 outdoors) -> GatherMate2 node id.

Node ids come from GatherMate2 1.27's Constants.lua (node_ids table, English names = gameobject names). They are kept in
gathermate2_node_ids.json next to this script; refresh it with:
  py -I gen_gather_data.py --extract <path to GatherMate2 1.27 Constants.lua>
Then: py -I gen_gather_data.py  (writes arpg/addons/ArpgGatherData/Data.lua), arpg/scripts/install-addons.ps1.
"""
import json
import os
import re
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
MYSQL = r'C:\Program Files\MySQL\MySQL Server 8.0\bin\mysql.exe'
CNF = os.path.join(ROOT, 'arpg', 'scripts', 'mysql.local.cnf')
DBC = os.path.join(os.path.dirname(ROOT), 'ServerData', 'data', 'dbc', 'WorldMapArea.dbc')
IDS = os.path.join(HERE, 'gathermate2_node_ids.json')
OUT = os.path.join(ROOT, 'arpg', 'addons', 'ArpgGatherData', 'Data.lua')
TYPES = ('Fishing', 'Mining', 'Extract Gas', 'Herb Gathering', 'Treasure')


def extract(constants_path):
    """node_ids from GatherMate2's Constants.lua: { type: { English name: id } } (commented-out lines skipped)."""
    text = open(constants_path, encoding='utf-8').read()
    start = text.index('local node_ids = {')
    body = text[start:text.index('\n}\n', start)]
    ids, cur = {}, None
    for line in body.splitlines():
        s = line.strip()
        m = re.match(r'^\["([^"]+)"\]\s*=\s*\{', s)
        if m:
            cur = m.group(1)
            ids[cur] = {}
            continue
        m = re.match(r'^\[NL\["([^"]+)"\]\]\s*=\s*(\d+)', s)
        if m and cur:
            ids[cur][m.group(1)] = int(m.group(2))
    json.dump(ids, open(IDS, 'w', encoding='utf-8'), indent=1, sort_keys=True)
    print('wrote %s: %s' % (IDS, ', '.join('%s %d' % (k, len(v)) for k, v in sorted(ids.items()))))


def q(sql):
    out = subprocess.run([MYSQL, '--defaults-extra-file=' + CNF, '-D', 'world', '-B', '-N', '-e', sql],
                         capture_output=True, text=True, check=True).stdout
    return [line.split('\t') for line in out.splitlines() if line]


def world_map_areas():
    """(map, area) -> (WorldMapArea id, left, right, top, bottom); the zone-level entry (no dungeon floor map)."""
    d = open(DBC, 'rb').read()
    _, n, fields, rsize, _ = struct.unpack('<4s4I', d[:20])
    areas = {}
    for i in range(n):
        row = d[20 + i * rsize:20 + (i + 1) * rsize]
        wid, mp, area = struct.unpack('<3I', row[:12])
        left, right, top, bottom = struct.unpack('<4f', row[16:32])
        dungeon_map = struct.unpack('<i', row[36:40])[0]
        if area == 0 or dungeon_map > 0 or left == right or top == bottom:
            continue
        key = (mp, area)
        size = abs((left - right) * (top - bottom))
        if key not in areas or size > areas[key][5]:
            areas[key] = (wid, left, right, top, bottom, size)
    return areas


def main():
    ids = json.load(open(IDS, encoding='utf-8'))
    by_name = {}
    for t in TYPES:
        for name, nid in ids.get(t, {}).items():
            by_name.setdefault(name, (t, nid))
    areas = world_map_areas()
    rows = q("SELECT t.name, g.map, g.zoneId, g.areaId, g.position_x, g.position_y FROM gameobject g "
             "JOIN gameobject_template t ON t.entry = g.id WHERE t.type IN (3, 25) AND g.zoneId <> 0")
    data = {t: {} for t in TYPES}
    seen = set()
    placed = unmapped = 0
    for name, mp, zone, area, x, y in rows:
        hit = by_name.get(name)
        if not hit:
            continue
        a = areas.get((int(mp), int(zone))) or areas.get((int(mp), int(area)))
        if not a:
            unmapped += 1
            continue
        wid, left, right, top, bottom, _ = a
        px = (left - float(y)) / (left - right)
        py = (top - float(x)) / (top - bottom)
        if not (0.0 <= px < 1.0 and 0.0 <= py < 1.0):
            unmapped += 1
            continue
        px, py = min(px, 0.9999), min(py, 0.9999)
        coord = int(px * 10000 + 0.5) * 1000000 + int(py * 10000 + 0.5) * 100
        t, nid = hit
        if (t, wid, coord) in seen:
            continue
        seen.add((t, wid, coord))
        data[t].setdefault(wid, []).extend((coord, nid))
        placed += 1
    version = len(seen)
    lines = ['-- GENERATED by modules/mod_arpg/sql/tools/gen_gather_data.py from the world DB - do not edit by hand.',
             'ArpgGatherData = {', '    version = %d,' % version]
    for t in TYPES:
        lines.append('    ["%s"] = {' % t)
        for wid in sorted(data[t]):
            lines.append('        [%d] = {%s},' % (wid, ','.join(str(v) for v in data[t][wid])))
        lines.append('    },')
    lines.append('}')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote %s: %d nodes (%s), %d spawns not on a zone map' % (
        OUT, placed, ', '.join('%s %d' % (t, sum(len(v) // 2 for v in data[t].values())) for t in TYPES), unmapped))


if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] == '--extract':
        extract(sys.argv[2])
    else:
        main()
