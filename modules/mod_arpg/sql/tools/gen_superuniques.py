"""Generates sql/world/2026_11_27_02_arpg_superunique_world.sql: Superuniques in every open-world zone (owner 2026-11-27:
"populate the world with superuniques"). The three hand-made zones (Dun Morogh 1, Elwynn 12, Westfall 40, ids < 1000) stay as
they are; every other zone gets up to PER_ZONE of its own rare creatures (rank 2 Rare Elite / 4 Rare) as its pool, ids 1000+,
ability kits alternating, spawn points = that creature's own spawns in the zone (up to POINTS). Afterwards re-run
gen_monster_tags.py: it makes the "Unique <name>" copies from arpg_superunique. Idempotent; re-run after a DB update.
Usage: py -I gen_superuniques.py
"""
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
MYSQL = r'C:\Program Files\MySQL\MySQL Server 8.0\bin\mysql.exe'
CNF = os.path.join(ROOT, 'arpg', 'scripts', 'mysql.local.cnf')
OUT = os.path.join(HERE, '..', 'world', '2026_11_27_02_arpg_superunique_world.sql')

OPEN_WORLD_MAPS = '0,1,530,571,870,860,654,648,646,638,1064'   # same as gen_monster_tags.py
HAND_MADE_ZONES = (1, 12, 40)
PER_ZONE = 8
POINTS = 6
KITS = (1, 2)
FIRST_ID = 1000
MAX_BASE_ENTRY = 299999   # the "Unique" copy lives at entry + 700000 and must stay below the companion (1,000,001)


def q(sql):
    out = subprocess.run([MYSQL, '--defaults-extra-file=' + CNF, '-D', 'world', '-B', '-N', '-e', sql],
                         capture_output=True, text=True, check=True).stdout
    return [line.split('\t') for line in out.splitlines() if line]


rows = q("SELECT c.zoneId, t.entry, c.guid, c.map, c.position_x, c.position_y, c.position_z, c.orientation "
         "FROM creature c JOIN creature_template t ON t.entry = c.id "
         "WHERE c.map IN (%s) AND t.`rank` IN (2, 4) AND c.zoneId <> 0 AND c.zoneId NOT IN (%s) AND t.npcflag = 0 "
         "AND t.type <> 8 AND t.entry <= %d ORDER BY c.zoneId, t.entry, c.guid"
         % (OPEN_WORLD_MAPS, ','.join(str(z) for z in HAND_MADE_ZONES), MAX_BASE_ENTRY))

zones = {}
for zone, entry, guid, mp, x, y, z, o in rows:
    zones.setdefault(int(zone), {}).setdefault(int(entry), []).append((int(guid), int(mp), x, y, z, o))

sql = ['-- GENERATED by sql/tools/gen_superuniques.py - do not edit by hand. Idempotent.',
       '-- Superuniques in every open-world zone: each zone\'s own rares (ids %d+); hand-made zones %s unchanged.'
       % (FIRST_ID, ', '.join(str(z) for z in HAND_MADE_ZONES)),
       'DELETE FROM `arpg_superunique_spawn` WHERE `superunique_id` >= %d;' % FIRST_ID,
       'DELETE FROM `arpg_superunique_unique` WHERE `superunique_id` >= %d;' % FIRST_ID,
       'DELETE FROM `arpg_superunique` WHERE `id` >= %d;' % FIRST_ID, '']
next_id = FIRST_ID
pools = spawns = 0
for zone in sorted(zones):
    for n, entry in enumerate(sorted(zones[zone])[:PER_ZONE]):
        sql.append('INSERT INTO `arpg_superunique` (`id`, `zone_id`, `creature_entry`, `kit_id`, `weight`) VALUES (%d, %d, %d, %d, 100);'
                   % (next_id, zone, entry, KITS[n % len(KITS)]))
        pts = zones[zone][entry][:POINTS]
        sql.append('INSERT INTO `arpg_superunique_spawn` (`superunique_id`, `point`, `map`, `x`, `y`, `z`, `o`) VALUES %s;'
                   % ', '.join('(%d, %d, %d, %s, %s, %s, %s)' % (next_id, g, mp, x, y, z, o) for g, mp, x, y, z, o in pts))
        next_id += 1
        pools += 1
        spawns += len(pts)
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(sql) + '\n')
print('wrote %s: %d zones, %d superuniques, %d spawn points' % (OUT, len(zones), pools, spawns))
