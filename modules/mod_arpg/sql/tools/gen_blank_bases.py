"""Generates sql/world/2026_11_27_03_arpg_blank_bases.sql: typed blank bases (owner 2026-11-22 BALANCE 8c, use decided
2026-11-27: "all of these" = drops, crafting targets and the companion's essence shop).

A blank base is a copy of a real, droppable item (same look, armour / weapon damage, sockets, quality) that keeps only two
stat lines: its armour type's main stat + Stamina, at the original's own values. Everything else comes from affixes, and a
dropped or bought blank always rolls the most affixes for its quality (mod_arpg Loot/Blanks).

One blank per (slot, item class/subclass, quality, 10-level bracket of RequiredLevel, main stat variant); the original is the
candidate whose RequiredLevel is highest in the bracket. Ids FIRST_ID+ (custom item range, below the mount copies at 800000).
Idempotent; re-run after a world DB update. Usage: py -I gen_blank_bases.py
"""
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
MYSQL = r'C:\Program Files\MySQL\MySQL Server 8.0\bin\mysql.exe'
CNF = os.path.join(ROOT, 'arpg', 'scripts', 'mysql.local.cnf')
OUT = os.path.join(HERE, '..', 'world', '2026_11_27_03_arpg_blank_bases.sql')

FIRST_ID, LAST_ID = 710000, 799999
STR, AGI, INT, STA = 4, 3, 5, 7
BRACKET = 10
DESCRIPTION = 'Blank base: always rolls the most affixes for its quality.'

# Armour (class 4): inventory types that get blanks, and the main stats per armour subclass.
ARMOR_SLOTS = (1, 3, 5, 6, 7, 8, 9, 10, 20)          # head shoulder chest waist legs feet wrist hands robe
ARMOR_MAIN = {1: (INT,), 2: (AGI, INT), 3: (AGI, INT), 4: (STR, INT)}
JEWELRY_SLOTS = (2, 11, 16)                           # neck, finger, back (any armour subclass)
SHIELD_SUB, HELD_INV = 6, 23
# Weapons (class 2): subclass -> main stats.
WEAPON_MAIN = {0: (STR, AGI), 1: (STR,), 2: (AGI,), 3: (AGI,), 4: (STR, INT), 5: (STR,), 6: (STR, AGI), 7: (STR, AGI, INT),
               8: (STR,), 10: (INT, AGI), 13: (AGI,), 15: (AGI, INT), 18: (AGI,), 19: (INT,)}


def q(sql):
    out = subprocess.run([MYSQL, '--defaults-extra-file=' + CNF, '-D', 'world', '-B', '-N', '-e', sql],
                         capture_output=True, text=True, check=True).stdout
    return [line.split('\t') for line in out.splitlines() if line]


def mains_for(cls, sub, inv):
    if cls == 2:
        return WEAPON_MAIN.get(sub, ())
    if inv in JEWELRY_SLOTS:
        return (STR, AGI, INT)
    if sub == SHIELD_SUB:
        return (STR, INT)
    if inv == HELD_INV:
        return (INT,)
    if inv in ARMOR_SLOTS:
        return ARMOR_MAIN.get(sub, ())
    return ()


stat_cols = ', '.join('stat_type%d, stat_value%d' % (i, i) for i in range(1, 11))
# Droppable = appears in a loot table (as Loot/Substitution's candidate index); read separately, the IN (... UNION ...) form
# takes minutes.
drops = set()
for table in ('creature_loot_template', 'reference_loot_template', 'gameobject_loot_template'):
    drops.update(int(r[0]) for r in q('SELECT DISTINCT item FROM %s' % table))
rows = [r for r in q("SELECT entry, class, subclass, InventoryType, Quality, RequiredLevel, %s FROM item_template "
                     "WHERE entry < %d AND class IN (2, 4) AND Quality BETWEEN 2 AND 4 AND RequiredLevel BETWEEN 1 AND 90 "
                     "AND RandomProperty = 0 AND RandomSuffix = 0 ORDER BY entry" % (stat_cols, FIRST_ID))
        if int(r[0]) in drops]

best = {}   # (inv, class, sub, quality, bracket) -> (requiredLevel, entry, main value, stamina)
for r in rows:
    entry, cls, sub, inv, quality, req = (int(x) for x in r[:6])
    if not mains_for(cls, sub, inv):
        continue
    stats = {}
    for i in range(10):
        t, v = int(r[6 + 2 * i]), int(r[7 + 2 * i])
        if t and v > 0:
            stats[t] = stats.get(t, 0) + v
    total = sum(stats.values())
    if total <= 0:
        continue   # stat-less originals (some low greens) have no budget to copy
    main = max(stats.get(STR, 0), stats.get(AGI, 0), stats.get(INT, 0)) or max(1, (total * 55 + 99) // 100)
    sta = stats.get(STA, 0) or max(1, (total * 45 + 99) // 100)
    key = (inv, cls, sub, quality, (req + BRACKET - 1) // BRACKET * BRACKET)
    if key not in best or (req, -entry) > (best[key][0], -best[key][1]):
        best[key] = (req, entry, main, sta)

blanks = []   # (id, base, inv, class, sub, quality, bracket, main stat, main value, stamina)
nid = FIRST_ID
for key in sorted(best):
    inv, cls, sub, quality, bracket = key
    req, entry, main, sta = best[key]
    for stat in mains_for(cls, sub, inv):
        blanks.append((nid, entry, inv, cls, sub, quality, bracket, stat, main, sta))
        nid += 1
assert nid <= LAST_ID, 'too many blanks'

sql = ['-- Generated by modules/mod_arpg/sql/tools/gen_blank_bases.py - typed blank bases (%d items). Idempotent.' % len(blanks),
       '-- Do not edit; change the generator and re-run it.',
       'CREATE TABLE IF NOT EXISTS `arpg_blank` (',
       '  `entry` INT UNSIGNED NOT NULL PRIMARY KEY,',
       '  `base_item` INT UNSIGNED NOT NULL,',
       '  `inventory_type` TINYINT UNSIGNED NOT NULL,',
       '  `item_class` TINYINT UNSIGNED NOT NULL,',
       '  `subclass` TINYINT UNSIGNED NOT NULL,',
       '  `quality` TINYINT UNSIGNED NOT NULL,',
       '  `bracket` TINYINT UNSIGNED NOT NULL COMMENT \'top RequiredLevel of its 10-level bracket\',',
       '  `main_stat` TINYINT UNSIGNED NOT NULL COMMENT \'ITEM_MOD_* (4 Str, 3 Agi, 5 Int)\',',
       '  `main_value` INT NOT NULL,',
       '  `stamina` INT NOT NULL',
       ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT=\'mod_arpg typed blank bases (BALANCE 8c)\';',
       'DELETE FROM `arpg_blank`;']
for i in range(0, len(blanks), 500):
    sql.append('INSERT INTO `arpg_blank` VALUES')
    sql.append(',\n'.join('(%d,%d,%d,%d,%d,%d,%d,%d,%d,%d)' % b for b in blanks[i:i + 500]) + ';')

stat_reset = ', '.join('t.`stat_type%d` = 0, t.`stat_value%d` = 0' % (i, i) for i in range(3, 11))
spell_reset = ', '.join('t.`spellid_%d` = 0, t.`spelltrigger_%d` = 0' % (i, i) for i in range(1, 6))
sql += ['DELETE FROM `item_template` WHERE `entry` BETWEEN %d AND %d;' % (FIRST_ID, LAST_ID),
        'DROP TEMPORARY TABLE IF EXISTS `arpg_tmp_it`;',
        'CREATE TEMPORARY TABLE `arpg_tmp_it` LIKE `item_template`;',
        'INSERT INTO `arpg_tmp_it` SELECT i.* FROM `item_template` i JOIN (SELECT DISTINCT `base_item` FROM `arpg_blank`) b '
        'ON b.`base_item` = i.`entry`;',
        'DROP TEMPORARY TABLE IF EXISTS `arpg_tmp_bl`;',
        'CREATE TEMPORARY TABLE `arpg_tmp_bl` LIKE `item_template`;']
# One copy per blank: the base row with the blank's id and its two stat lines; then everything else is cleared at once.
for b in blanks:
    nid, base, inv, cls, sub, quality, bracket, stat, main, sta = b
    sql.append('INSERT INTO `arpg_tmp_bl` SELECT * FROM `arpg_tmp_it` WHERE `entry` = %d;' % base)
    sql.append('UPDATE `arpg_tmp_bl` SET `entry` = %d, `stat_type1` = %d, `stat_value1` = %d, `stat_type2` = 7, '
               '`stat_value2` = %d WHERE `entry` = %d;' % (nid, stat, main, sta, base))
sql += ['UPDATE `arpg_tmp_bl` t SET %s, %s, t.`itemset` = 0, t.`RandomProperty` = 0, t.`RandomSuffix` = 0, '
        't.`ScalingStatDistribution` = 0, t.`ScalingStatValue` = 0, t.`description` = "%s";'
        % (stat_reset, spell_reset, DESCRIPTION),
        'INSERT INTO `item_template` SELECT * FROM `arpg_tmp_bl`;',
        'DROP TEMPORARY TABLE `arpg_tmp_bl`;',
        'DROP TEMPORARY TABLE `arpg_tmp_it`;',
        '-- The client reads the copies from the server (Item + Item-sparse hotfixes).',
        'DELETE FROM `hotfix_data` WHERE `entry` BETWEEN %d AND %d AND `type` IN (1344507586, 2442913102);' % (FIRST_ID, LAST_ID),
        'INSERT INTO `hotfix_data` (`entry`, `type`, `hotfixDate`) SELECT `entry`, 1344507586, \'2026-11-27 09:00:00\' FROM `arpg_blank` '
        'UNION ALL SELECT `entry`, 2442913102, \'2026-11-27 09:00:00\' FROM `arpg_blank`;']
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(sql) + '\n')
print('blanks=%d (groups=%d) -> %s' % (len(blanks), len(best), OUT))
