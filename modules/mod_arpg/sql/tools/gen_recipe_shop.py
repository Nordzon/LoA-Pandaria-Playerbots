"""Generates sql/world/2026_11_28_05_arpg_recipe_shop.sql (change m10-companion-professions, owner 2026-11-28: "each profession
sub-menu will also have the profession-specific recipes that you usually get from rep grind and dailies sold for gold").

Recipes picked: recipe items (class 9) sold by a vendor that needs reputation (item RequiredReputationFaction) or tokens /
currency (npc_vendor.ExtendedCost), or rewarded by daily / weekly quests. Each gets a copy at COPY_OFFSET + its id with no
reputation, faction or race limit and a gold price from arpg_recipe_price (by the recipe's required skill; epic x2), sold by
one hidden vendor per profession page (VENDOR_BASE + profession index * 10 + page, <= 150 items a page: the client limit).
The companion's Professions menu opens those pages (arpg_recipe_shop). Re-run after a DB update; the SQL is idempotent.
Usage: py -I gen_recipe_shop.py
"""
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
MYSQL = r'C:\Program Files\MySQL\MySQL Server 8.0\bin\mysql.exe'
CNF = os.path.join(ROOT, 'arpg', 'scripts', 'mysql.local.cnf')
OUT = os.path.join(HERE, '..', 'world', '2026_11_28_05_arpg_recipe_shop.sql')

COPY_OFFSET = 1100000      # copies 1,100,000+ (mount copies use 800,000+, custom items 700,000+)
VENDOR_BASE = 1000100      # hidden vendor creatures 1,000,100+ (companion is 1,000,001, mount merchant 1,000,002)
PAGE = 150                 # MAX_VENDOR_ITEMS
# Skill lines in menu order: the 11 primary professions, then Cooking, First Aid, Fishing.
SKILLS = [171, 164, 333, 202, 182, 773, 755, 165, 186, 393, 197, 185, 129, 356]


def q(sql):
    out = subprocess.run([MYSQL, '--defaults-extra-file=' + CNF, '-D', 'world', '-B', '-N', '-e', sql],
                         capture_output=True, text=True, check=True).stdout
    return [line.split('\t') for line in out.splitlines() if line]


rows = q("""
SELECT DISTINCT i.entry, i.RequiredSkill, i.RequiredSkillRank FROM item_template i
WHERE i.class = 9 AND i.entry < 1000000 AND i.RequiredSkill IN (%s) AND (
      (i.RequiredReputationFaction > 0 AND i.entry IN (SELECT item FROM npc_vendor WHERE item > 0))
   OR i.entry IN (SELECT item FROM npc_vendor WHERE ExtendedCost > 0)
   OR i.entry IN (SELECT x FROM (
        SELECT RewardItem1 x, Flags FROM quest_template UNION ALL SELECT RewardItem2, Flags FROM quest_template
        UNION ALL SELECT RewardItem3, Flags FROM quest_template UNION ALL SELECT RewardItem4, Flags FROM quest_template
        UNION ALL SELECT RewardChoiceItemID1, Flags FROM quest_template UNION ALL SELECT RewardChoiceItemID2, Flags FROM quest_template
        UNION ALL SELECT RewardChoiceItemID3, Flags FROM quest_template UNION ALL SELECT RewardChoiceItemID4, Flags FROM quest_template
        UNION ALL SELECT RewardChoiceItemID5, Flags FROM quest_template UNION ALL SELECT RewardChoiceItemID6, Flags FROM quest_template
      ) r WHERE r.x > 0 AND (r.Flags & 0x1000 OR r.Flags & 0x8000)))
ORDER BY i.RequiredSkill, i.RequiredSkillRank, i.entry""" % ','.join(str(s) for s in SKILLS))

by_skill = {}
for entry, skill, _rank in rows:
    by_skill.setdefault(int(skill), []).append(int(entry))

shop = []   # (skill, page, vendor, item)
for idx, skill in enumerate(SKILLS):
    items = by_skill.get(skill, [])
    for n, item in enumerate(items):
        page = n // PAGE
        shop.append((skill, page, VENDOR_BASE + idx * 10 + page, item))
vendors = sorted({(v, s, p) for s, p, v, _ in shop})

sql = ['-- GENERATED by sql/tools/gen_recipe_shop.py - do not edit by hand. Idempotent.',
       '-- Companion recipe shop (m10-companion-professions): reputation / token / daily recipes for gold, one hidden vendor per',
       '-- profession page; copies at %d + id without reputation, faction or race limits.' % COPY_OFFSET,
       '',
       'CREATE TABLE IF NOT EXISTS `arpg_recipe_price` (',
       '  `max_skill`  SMALLINT UNSIGNED NOT NULL COMMENT \'recipes up to this required skill ...\',',
       '  `price_gold` INT UNSIGNED NOT NULL COMMENT \'... cost this much (epic recipes x2)\',',
       '  PRIMARY KEY (`max_skill`)',
       ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;',
       '-- Prices (owner: "not easy to get, but bearable"): only filled when empty, so tuning in the table survives a re-run.',
       'INSERT IGNORE INTO `arpg_recipe_price` (`max_skill`, `price_gold`) VALUES (300, 25), (375, 75), (450, 150), (525, 300), (600, 600);',
       '',
       'DROP TABLE IF EXISTS `arpg_recipe_shop`;',
       'CREATE TABLE `arpg_recipe_shop` (',
       '  `skill`   SMALLINT UNSIGNED NOT NULL,',
       '  `page`    TINYINT UNSIGNED NOT NULL,',
       '  `vendor`  INT UNSIGNED NOT NULL COMMENT \'hidden vendor creature entry\',',
       '  `item_id` INT UNSIGNED NOT NULL COMMENT \'original recipe item; the copy sold is %d + item_id\',' % COPY_OFFSET,
       '  PRIMARY KEY (`item_id`), KEY (`skill`, `page`)',
       ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;']
for i in range(0, len(shop), 400):
    sql.append('INSERT INTO `arpg_recipe_shop` (`skill`, `page`, `vendor`, `item_id`) VALUES %s;'
               % ', '.join('(%d, %d, %d, %d)' % r for r in shop[i:i + 400]))

sql += ['',
        '-- Hidden vendors (copies of the companion template, only their vendor lists are used).',
        'DELETE FROM `creature_template_model` WHERE `CreatureID` BETWEEN %d AND %d;' % (VENDOR_BASE, VENDOR_BASE + 199),
        'DELETE FROM `creature_template` WHERE `entry` BETWEEN %d AND %d;' % (VENDOR_BASE, VENDOR_BASE + 199),
        'DROP TEMPORARY TABLE IF EXISTS `arpg_tmp_ct`;',
        'CREATE TEMPORARY TABLE `arpg_tmp_ct` LIKE `creature_template`;']
for v, s, p in vendors:
    sql.append("INSERT INTO `arpg_tmp_ct` SELECT * FROM `creature_template` WHERE `entry` = 1000001;")
    sql.append("UPDATE `arpg_tmp_ct` SET `entry` = %d, `name` = 'Recipe Merchant', `subname` = 'ARPG', `npcflag` = 128, "
               "`ScriptName` = '' WHERE `entry` = 1000001;" % v)
sql += ['INSERT INTO `creature_template` SELECT * FROM `arpg_tmp_ct`;',
        'DROP TEMPORARY TABLE `arpg_tmp_ct`;']
for v, s, p in vendors:
    sql.append('INSERT INTO `creature_template_model` (`CreatureID`, `Idx`, `CreatureDisplayID`, `DisplayScale`, `Probability`, '
               '`VerifiedBuild`) SELECT %d, `Idx`, `CreatureDisplayID`, `DisplayScale`, `Probability`, `VerifiedBuild` '
               'FROM `creature_template_model` WHERE `CreatureID` = 1000001;' % v)

sql += ['',
        '-- Recipe copies: no reputation / faction / race limit, gold price by required skill (epic x2), no sell value.',
        'DELETE FROM `item_template` WHERE `entry` BETWEEN %d AND %d;' % (COPY_OFFSET, COPY_OFFSET + 999999),
        'DROP TEMPORARY TABLE IF EXISTS `arpg_tmp_it`;',
        'CREATE TEMPORARY TABLE `arpg_tmp_it` LIKE `item_template`;',
        'INSERT INTO `arpg_tmp_it` SELECT i.* FROM `item_template` i JOIN `arpg_recipe_shop` s ON s.`item_id` = i.`entry`;',
        'UPDATE `arpg_tmp_it` t SET',
        '  t.`BuyPrice` = 10000 * IF(t.`Quality` >= 4, 2, 1) * IFNULL((SELECT MIN(p.`price_gold`) FROM `arpg_recipe_price` p',
        '      WHERE p.`max_skill` >= t.`RequiredSkillRank`), (SELECT MAX(p.`price_gold`) FROM `arpg_recipe_price` p)),',
        '  t.`BuyCount` = 1, t.`SellPrice` = 0,',
        '  t.`RequiredReputationFaction` = 0, t.`RequiredReputationRank` = 0,',
        '  t.`AllowableRace` = -1, t.`AllowableClass` = -1,',
        '  t.`FlagsExtra` = t.`FlagsExtra` & ~3,',
        '  t.`entry` = %d + t.`entry`;' % COPY_OFFSET,
        'INSERT INTO `item_template` SELECT * FROM `arpg_tmp_it`;',
        'DROP TEMPORARY TABLE `arpg_tmp_it`;',
        '',
        '-- The client reads new items from the server (Item.db2 1344507586, Item-sparse.db2 2442913102).',
        'DELETE FROM `hotfix_data` WHERE `entry` BETWEEN %d AND %d AND `type` IN (1344507586, 2442913102);'
        % (COPY_OFFSET, COPY_OFFSET + 999999),
        "INSERT INTO `hotfix_data` (`entry`, `type`, `hotfixDate`) SELECT %d + `item_id`, 1344507586, '2026-11-28 15:30:00' "
        "FROM `arpg_recipe_shop`;" % COPY_OFFSET,
        "INSERT INTO `hotfix_data` (`entry`, `type`, `hotfixDate`) SELECT %d + `item_id`, 2442913102, '2026-11-28 15:30:00' "
        "FROM `arpg_recipe_shop`;" % COPY_OFFSET,
        '',
        '-- Vendor lists, cheapest first.',
        'DELETE FROM `npc_vendor` WHERE `entry` BETWEEN %d AND %d;' % (VENDOR_BASE, VENDOR_BASE + 199),
        'SET @slot := 0;',
        'INSERT INTO `npc_vendor` (`entry`, `slot`, `item`, `maxcount`, `incrtime`, `ExtendedCost`, `type`)',
        'SELECT s.`vendor`, (@slot := @slot + 1), %d + s.`item_id`, 0, 0, 0, 1 FROM `arpg_recipe_shop` s' % COPY_OFFSET,
        'JOIN `item_template` i ON i.`entry` = %d + s.`item_id` ORDER BY s.`vendor`, i.`BuyPrice`, i.`RequiredSkillRank`, s.`item_id`;'
        % COPY_OFFSET]
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(sql) + '\n')
counts = {}
for s, p, v, i in shop:
    counts[s] = counts.get(s, 0) + 1
print('wrote %s: %d recipes in %d vendor pages: %s' % (OUT, len(shop), len(vendors),
                                                     ', '.join('%d:%d' % kv for kv in sorted(counts.items()))))
