"""Generates sql/world/2026_11_22_08_arpg_monster_tags.sql: "tag" copies of creature templates for Champions and Superuniques
(owner 2026-11-22). The client takes a creature's name and portrait frame (rank) from its template, per entry - so a tagged
monster needs its own entry. Copies:
  Champion:    entry + 5000000, name "Champion <name>", rank 4 (Rare: silver dragon), every open-world type that can roll one
  Superunique: entry + 6000000, name "Unique <name>",   rank 2 (Rare Elite: winged silver dragon), arpg_superunique entries
Kill credit points back at the original (quests still count). Model, equipment, addon (auras) and movement rows are copied.
Offsets must match Arpg.Champion.EntryOffset / Arpg.Superunique.EntryOffset. Re-run after a DB update; the SQL is idempotent.
Usage: py -I gen_monster_tags.py   (reads the world DB via arpg/scripts/mysql.local.cnf)
"""
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
MYSQL = r'C:\Program Files\MySQL\MySQL Server 8.0\bin\mysql.exe'
CNF = os.path.join(ROOT, 'arpg', 'scripts', 'mysql.local.cnf')
OUT = os.path.join(HERE, '..', 'world', '2026_11_22_08_arpg_monster_tags.sql')

CHAMPION_OFFSET = 5000000
UNIQUE_OFFSET = 6000000
OPEN_WORLD_MAPS = '0,1,530,571,870,860,654,648,646,638,1064'


def cols(table):
    out = subprocess.run([MYSQL, '--defaults-extra-file=' + CNF, '-B', '-N', '-e',
                          "SELECT COLUMN_NAME FROM information_schema.COLUMNS WHERE TABLE_SCHEMA='world' AND TABLE_NAME='%s' "
                          "ORDER BY ORDINAL_POSITION" % table], capture_output=True, text=True, check=True).stdout
    return [c for c in out.split()]


def q(c):
    return '`%s`' % c


def copy_template(offset, prefix, rank, where):
    c = cols('creature_template')
    sel = []
    for name in c:
        if name == 'entry':
            sel.append('t.`entry` + %d' % offset)
        elif name.startswith('difficulty_entry_'):
            sel.append('0')
        elif name == 'KillCredit1':
            sel.append('IF(t.`KillCredit1` = 0, t.`entry`, t.`KillCredit1`)')
        elif name == 'KillCredit2':
            sel.append('IF(t.`KillCredit1` = 0, t.`KillCredit2`, t.`entry`)')
        elif name == 'name':
            sel.append("LEFT(CONCAT('%s ', t.`name`), 100)" % prefix)
        elif name == 'rank':
            sel.append(str(rank))
        elif name == 'AIName':
            sel.append("IF(t.`AIName` = 'SmartAI', '', t.`AIName`)")   # smart_scripts are keyed by the original entry
        else:
            sel.append('t.' + q(name))
    return ('INSERT INTO `creature_template` (%s)\nSELECT %s\nFROM `creature_template` t WHERE %s;\n'
            % (', '.join(q(x) for x in c), ', '.join(sel), where))


def copy_side(table, key, offset, where_entries):
    c = cols(table)
    sel = [('s.%s + %d' % (q(x), offset)) if x == key else 's.' + q(x) for x in c]
    return ('INSERT INTO %s (%s)\nSELECT %s\nFROM %s s WHERE s.%s IN (%s);\n'
            % (q(table), ', '.join(q(x) for x in c), ', '.join(sel), q(table), q(key), where_entries))


champion_where = ('t.`entry` < %d AND t.`rank` IN (0, 1) AND t.`type` <> 8 AND t.`entry` IN (SELECT DISTINCT `id` FROM `creature` '
                  'WHERE `map` IN (%s))' % (CHAMPION_OFFSET, OPEN_WORLD_MAPS))
champion_entries = ('SELECT `entry` FROM `creature_template` WHERE `entry` BETWEEN %d AND %d'
                    % (CHAMPION_OFFSET, UNIQUE_OFFSET - 1))
unique_where = 't.`entry` < %d AND t.`entry` IN (SELECT `creature_entry` FROM `arpg_superunique`)' % CHAMPION_OFFSET
unique_entries = 'SELECT `entry` FROM `creature_template` WHERE `entry` BETWEEN %d AND %d' % (UNIQUE_OFFSET, UNIQUE_OFFSET + 999999)

sql = ['-- GENERATED by sql/tools/gen_monster_tags.py - do not edit by hand. Idempotent.',
       '-- Champion / Superunique tag copies of creature templates (name + portrait rank per entry; owner 2026-11-22).',
       '-- Champion = entry + %d ("Champion <name>", rank 4 Rare), Superunique = entry + %d ("Unique <name>", rank 2 Rare Elite).'
       % (CHAMPION_OFFSET, UNIQUE_OFFSET), '']
side = [('creature_template_model', 'CreatureID'), ('creature_template_addon', 'entry'),
        ('creature_template_movement', 'CreatureId'), ('creature_equip_template', 'CreatureID')]
for table, key in side:
    sql.append('DELETE FROM %s WHERE %s BETWEEN %d AND %d;' % (q(table), q(key), CHAMPION_OFFSET, UNIQUE_OFFSET + 999999))
sql.append('DELETE FROM `creature_template` WHERE `entry` BETWEEN %d AND %d;' % (CHAMPION_OFFSET, UNIQUE_OFFSET + 999999))
sql.append('')
sql.append(copy_template(CHAMPION_OFFSET, 'Champion', 4, champion_where))
sql.append(copy_template(UNIQUE_OFFSET, 'Unique', 2, unique_where))
for offset, entries in ((CHAMPION_OFFSET, champion_entries), (UNIQUE_OFFSET, unique_entries)):
    originals = '(SELECT e - %d FROM (%s) x (e))' % (offset, entries.replace('SELECT `entry`', 'SELECT `entry` AS e'))
    for table, key in side:
        sql.append(copy_side(table, key, offset, 'SELECT `entry` - %d FROM `creature_template` WHERE `entry` BETWEEN %d AND %d'
                             % (offset, offset, offset + 999999)))
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(sql) + '\n')
print('wrote', OUT)
