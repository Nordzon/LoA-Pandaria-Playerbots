"""Generates modules/mod_arpg/sql/world/2026_11_22_05_arpg_zone_level.sql: each zone's normal level range, used by
world scaling (cap: max + Arpg.Scale.ZoneCapAbove) and loot (ceiling: max + Arpg.Loot.ZoneCeilingMargin). SPEC 4.1/4.2.

Source: the ORIGINAL quest levels per zone (arpg_quest_level_backup, saved before m1 made zone quests scale) joined with
quest_template.QuestSortID (= zone id). min = 10th percentile, max = 90th percentile. Zones with fewer than 5 quests or a
range wider than 30 levels (capital cities, mixed areas) get max 0 = no ceiling. Edit the output by hand if a zone needs it.
    py -I modules/mod_arpg/sql/tools/gen_zone_levels.py
"""
import collections, os, subprocess

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..', '..'))
MYSQL = r'C:\Program Files\MySQL\MySQL Server 8.0\bin\mysql.exe'
CNF = os.path.join(ROOT, 'arpg', 'scripts', 'mysql.local.cnf')
OUT = os.path.join(ROOT, 'modules', 'mod_arpg', 'sql', 'world', '2026_11_22_05_arpg_zone_level.sql')
MIN_QUESTS, MAX_SPREAD = 5, 30


def pct(xs, p):
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(p * (len(xs) - 1) + 0.5))]


def main():
    q = ("SELECT q.QuestSortID, b.QuestLevel FROM arpg_quest_level_backup b JOIN quest_template q ON q.ID = b.ID "
         "WHERE q.QuestSortID > 0 AND b.QuestLevel BETWEEN 1 AND 90")
    out = subprocess.run([MYSQL, '--defaults-extra-file=' + CNF, '-D', 'world', '-B', '-N', '-e', q],
                         capture_output=True, text=True, check=True).stdout
    zones = collections.defaultdict(list)
    for line in out.splitlines():
        if line.strip():
            zone, level = line.split('\t')
            zones[int(zone)].append(int(level))
    rows, capped = [], 0
    for zone in sorted(zones):
        lv = zones[zone]
        lo, hi = pct(lv, 0.1), pct(lv, 0.9)
        if len(lv) < MIN_QUESTS or hi - lo > MAX_SPREAD:
            hi = 0
        else:
            capped += 1
        rows.append(f'({zone}, {lo}, {hi}, {len(lv)})')
    sql = [
        '-- mod_arpg: normal level range per zone (SPEC 4.1 loot ceiling, 4.2 scaling cap). GENERATED by',
        '-- modules/mod_arpg/sql/tools/gen_zone_levels.py from the original quest levels. max_level 0 = no ceiling. Idempotent.',
        'CREATE TABLE IF NOT EXISTS `arpg_zone_level` (',
        '  `zone_id` INT UNSIGNED NOT NULL, `min_level` TINYINT UNSIGNED NOT NULL, `max_level` TINYINT UNSIGNED NOT NULL,',
        "  `quests` SMALLINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'quests the range was measured from',",
        '  PRIMARY KEY (`zone_id`)',
        ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='mod_arpg zone level ranges';",
        'DELETE FROM `arpg_zone_level`;',
        'INSERT INTO `arpg_zone_level` VALUES',
        ',\n'.join(rows) + ';',
    ]
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(sql) + '\n')
    print(f'wrote {OUT}: {len(rows)} zones, {capped} with a ceiling')


if __name__ == '__main__':
    main()
